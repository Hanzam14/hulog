export const strings = { en, tl, taglish };
export function readLang(): Lang {
  try {
    const value = localStorage.getItem("hulog-lang");
    if (value === "en" || value === "tl" || value === "taglish") return value;
  } catch {
    /* Device storage can be disabled. */
  }
  return "taglish";
}
let language = readLang();
const listeners = new Set<() => void>();
export const languageSnapshot = () => language;
export function subscribeLanguage(listener: () => void) {
  listeners.add(listener);
  return () => {
    listeners.delete(listener);
  };
}
function applyLanguage(value: Lang) {
  language = value;
  if (typeof document !== "undefined" && document.documentElement)
    document.documentElement.lang = value === "en" ? "en" : "tl";
  listeners.forEach((listener) => listener());
}
export function setLang(value: Lang) {
  try {
    localStorage.setItem("hulog-lang", value);
  } catch {
    /* Still apply this session. */
  }
  applyLanguage(value);
}
export function initializeLanguage() {
  applyLanguage(readLang());
  window.addEventListener("storage", (event) => {
    if (event.key === "hulog-lang" || event.key === null)
      applyLanguage(readLang());
  });
}
export function t(
  key: Key,
  vars: Record<string, string | number> = {},
): string {
  return strings[language][key].replace(/\{(\w+)\}/g, (match, name: string) =>
    Object.prototype.hasOwnProperty.call(vars, name)
      ? String(vars[name])
      : match,
  );
}
export function useLanguage() {
  return useSyncExternalStore(
    subscribeLanguage,
    languageSnapshot,
    languageSnapshot,
  );
}
/** Translate database enum labels; unknown history values remain intact. */
export function label(value: string): string {
  return Object.prototype.hasOwnProperty.call(taglish, value)
    ? t(value as Key)
    : value;
}
