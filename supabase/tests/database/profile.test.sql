select is((select nickname from profiles where id=auth.uid()),'Piggy','Nickname is trimmed');
select is((select avatar_emoji from profiles where id=auth.uid()),'🐷','Curated emoji saves');
select is((select color from profiles where id=auth.uid()),'green','Chosen color saves');
