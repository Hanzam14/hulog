 ('10000000-0000-0000-0000-000000000001','profile-a@hulog.test','{"full_name":"Google A","avatar_url":"https://example.invalid/a.png"}'),
 ('10000000-0000-0000-0000-000000000002','profile-b@hulog.test','{"full_name":"Google B"}');
create temporary table fixture(key text primary key,val text);
grant all on fixture to authenticated;
create function pg_temp.actor(n integer) returns void language sql as $$
 select set_config('request.jwt.claim.sub','10000000-0000-0000-0000-'||lpad(n::text,12,'0'),true)::text;
$$;
set local role authenticated;
select pg_temp.actor(1);
select create_group('Our profile test','Bank');
